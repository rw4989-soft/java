USE spongebob;

DROP TABLE IF EXISTS t_place;
DROP TABLE IF EXISTS t_category;

-- ----------------------------
-- 分类表（两级：parent_id = 0 为一级）
-- ----------------------------
CREATE TABLE t_category (
    id        BIGINT      NOT NULL COMMENT '主键ID',
    code      VARCHAR(30) NOT NULL COMMENT '分类编码（前端筛选用）',
    name      VARCHAR(30) NOT NULL COMMENT '分类名称',
    icon      VARCHAR(10)          DEFAULT NULL COMMENT '图标 emoji',
    parent_id BIGINT      NOT NULL DEFAULT 0 COMMENT '父分类ID，0 表示一级',
    sort_no   INT         NOT NULL DEFAULT 0 COMMENT '排序号',
    PRIMARY KEY (id),
    UNIQUE KEY uk_code (code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='分类表';

-- ----------------------------
-- 条目表
-- ----------------------------
CREATE TABLE t_place (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    name        VARCHAR(60)  NOT NULL COMMENT '名称',
    emoji       VARCHAR(10)           DEFAULT NULL COMMENT '图标 emoji',
    summary     VARCHAR(255)          DEFAULT NULL COMMENT '一句话简介',
    detail      TEXT                  COMMENT '详细介绍',
    grade       CHAR(1)      NOT NULL DEFAULT 'C' COMMENT '分级 S/A/B/C',
    grade_label VARCHAR(20)           DEFAULT NULL COMMENT '分级中文名',
    rating      DECIMAL(3, 1)         DEFAULT 0.0 COMMENT '评分',
    heat        INT          NOT NULL DEFAULT 0 COMMENT '热度',
    view_count  INT          NOT NULL DEFAULT 0 COMMENT '浏览次数',
    category_id BIGINT       NOT NULL COMMENT '所属分类ID',
    tags        VARCHAR(200)          DEFAULT NULL COMMENT '标签，逗号分隔',
    create_time DATETIME              DEFAULT NULL COMMENT '创建时间',
    update_time DATETIME              DEFAULT NULL COMMENT '更新时间',
    PRIMARY KEY (id),
    KEY idx_category (category_id),
    KEY idx_grade (grade),
    KEY idx_heat (heat)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='条目表';

